DROP POLICY IF EXISTS "Public read modules" ON public.course_modules;
CREATE POLICY "Public read modules" ON public.course_modules FOR SELECT TO anon USING (true);
DROP POLICY IF EXISTS "Anon full access modules" ON public.course_modules;
CREATE POLICY "Anon full access modules" ON public.course_modules FOR ALL TO anon USING (true) WITH CHECK (true);

-- course_lessons
DROP POLICY IF EXISTS "Admin full access lessons" ON public.course_lessons;
CREATE POLICY "Admin full access lessons" ON public.course_lessons FOR ALL TO authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Public read lessons" ON public.course_lessons;
CREATE POLICY "Public read lessons" ON public.course_lessons FOR SELECT TO anon USING (true);
DROP POLICY IF EXISTS "Anon full access lessons" ON public.course_lessons;
