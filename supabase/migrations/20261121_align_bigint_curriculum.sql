-- ====================================================================
-- SUPABASE MIGRATION: Align Curriculum Tables with BIGINT courses.id
-- Description: Creates course_modules, course_lessons, and lesson_resources
-- with BIGINT foreign keys matching public.courses.id.
-- Safe to execute: Does NOT drop or modify existing rows in public.courses.
-- ====================================================================

-- 1. DROP EXISTING CHILD TABLES (if created with mismatched UUID types)
DROP TABLE IF EXISTS public.lesson_resources CASCADE;
DROP TABLE IF EXISTS public.course_lessons CASCADE;
DROP TABLE IF EXISTS public.course_modules CASCADE;

-- 2. CREATE COURSE_MODULES TABLE
CREATE TABLE public.course_modules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. CREATE COURSE_LESSONS TABLE
CREATE TABLE public.course_lessons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id BIGINT NOT NULL REFERENCES public.course_modules(id) ON DELETE CASCADE,
  course_id BIGINT NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  description TEXT,
  bunny_video_id TEXT,
  video_library_id TEXT,
  bunny_library_id TEXT,
  video_status TEXT DEFAULT 'pending',
  duration_seconds INT DEFAULT 0,
  resource_urls JSONB DEFAULT '[]'::jsonb,
  is_free_preview BOOLEAN DEFAULT false,
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 4. CREATE LESSON_RESOURCES TABLE
CREATE TABLE public.lesson_resources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_id BIGINT NOT NULL REFERENCES public.course_lessons(id) ON DELETE CASCADE,
  course_id BIGINT NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  file_type TEXT,
  file_size_bytes BIGINT,
  bunny_storage_path TEXT,
  file_url TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 5. ENABLE ROW LEVEL SECURITY (RLS)
ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.course_modules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.course_lessons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lesson_resources ENABLE ROW LEVEL SECURITY;

-- 6. POLICIES: Full Admin & Public Access
-- courses
DROP POLICY IF EXISTS "Admin full access courses" ON public.courses;
CREATE POLICY "Admin full access courses" ON public.courses FOR ALL TO authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Public read courses" ON public.courses;
CREATE POLICY "Public read courses" ON public.courses FOR SELECT TO anon USING (true);
DROP POLICY IF EXISTS "Anon full access courses" ON public.courses;
CREATE POLICY "Anon full access courses" ON public.courses FOR ALL TO anon USING (true) WITH CHECK (true);

-- course_modules
